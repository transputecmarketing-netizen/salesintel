// Writes src/brand/lucide-icons.js with only the Lucide icons the project uses, so pages
// download a few dozen icons instead of all 2,000+. Any kebab-case string literal in the
// source that names a Lucide icon is included (a small superset is fine).
// Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

const root = fileURLToPath(new URL('..', import.meta.url));
// The same name → export mapping src/brand/lucide.js uses at runtime.
const pascal = (name) => name.replace(/(^|[-_ ])(\w)/g, (_, __, c) => c.toUpperCase());
const skip = new Set(['node_modules', 'dist', '.git', 'vendor', 'public']);
const used = new Set();

function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (!['.js', '.html'].includes(extname(name)) || p.endsWith('lucide-icons.js')) continue;
    const src = readFileSync(p, 'utf8');
    for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) {
      const exp = pascal(m[1]);
      if (icons[exp]) used.add(exp);
    }
  }
}
walk(root);

const names = [...used].sort();
writeFileSync(join(root, 'src/brand/lucide-icons.js'), `// Generated by scripts/build-icons.mjs: the Lucide icons this project uses. Do not edit.
import { ${names.join(', ')} } from 'lucide';

export const icons = { ${names.join(', ')} };
`);
console.log(`icons: ${names.length} of ${Object.keys(icons).length} Lucide icons → src/brand/lucide-icons.js`);
